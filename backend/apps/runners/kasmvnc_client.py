"""Pinned desktop web clients served by the desktop proxy.

The viewer runs on the platform origin, so its HTML and JavaScript must never
be whatever an untrusted workspace returns. Only files of a pinned client
release (``kasmvnc_client.json`` for Linux guests, ``novnc_client.json`` for
Windows guests whose display QEMU serves; generated by
``scripts/kasmvnc_client_manifest.py``) are served, and only when the bytes the
desktop upstream returns match the recorded SHA-256. Verified files are cached
by digest, so later viewers no longer read them from any workspace.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from functools import cache
from pathlib import Path, PurePosixPath

KASMVNC = "kasmvnc"
NOVNC = "novnc"
_MANIFESTS = {
    KASMVNC: Path(__file__).with_name("kasmvnc_client.json"),
    NOVNC: Path(__file__).with_name("novnc_client.json"),
}

_CONTENT_TYPES = {
    ".css": "text/css; charset=utf-8",
    ".gif": "image/gif",
    ".html": "text/html; charset=utf-8",
    ".jpg": "image/jpeg",
    ".js": "text/javascript; charset=utf-8",
    ".json": "application/json",
    ".mp3": "audio/mpeg",
    ".oga": "audio/ogg",
    ".png": "image/png",
    ".svg": "image/svg+xml",
    ".ttf": "font/ttf",
    ".woff": "font/woff",
}

# Bounded by the manifest (about 4 MiB) and shared by every workspace.
_VERIFIED: dict[str, bytes] = {}


@dataclass(frozen=True)
class ClientFile:
    """One file of a pinned desktop web client."""

    path: str
    sha256: str
    content_type: str


@cache
def _manifest(client: str = KASMVNC) -> dict[str, object]:
    return json.loads(_MANIFESTS[client].read_text())


def client_for_guest(guest_os: str | None) -> str:
    """Return the viewer of a guest OS: noVNC for QEMU's display (Windows)."""
    return NOVNC if guest_os == "windows" else KASMVNC


def client_version(client: str = KASMVNC) -> str:
    """Return the pinned client release, e.g. ``1.3.3``."""
    return str(_manifest(client)["version"])


def client_files(client: str = KASMVNC) -> dict[str, str]:
    """Return the pinned client files and their SHA-256 digests."""
    return dict(_manifest(client)["files"])  # type: ignore[arg-type]


def lookup_client_file(rest_path: str, client: str = KASMVNC) -> ClientFile | None:
    """Return the pinned file for a proxied path such as ``/vnc.html``."""
    relative = rest_path.removeprefix("/")
    digest = client_files(client).get(relative)
    content_type = _CONTENT_TYPES.get(PurePosixPath(relative).suffix)
    if digest is None or content_type is None:
        return None
    return ClientFile(path=relative, sha256=digest, content_type=content_type)


def cached_client_file(file: ClientFile) -> bytes | None:
    """Return the verified bytes of *file* if any workspace already served them."""
    return _VERIFIED.get(file.sha256)


def accept_client_file(file: ClientFile, body: bytes) -> bool:
    """Cache *body* and return True only if it is the pinned file."""
    if hashlib.sha256(body).hexdigest() != file.sha256:
        return False
    _VERIFIED[file.sha256] = body
    return True
