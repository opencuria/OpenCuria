#!/usr/bin/env node
// Writes src/tools/files/fileIconSvgs.generated.ts from the webapp's
// material-icon-theme SVGs (MIT), keeping only keys the shared resolver
// (`@opencuria/chat-core/fileIcons`) can return.
// Usage (from the repository root): node mobile/scripts/generate-file-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const mobile = join(dirname(fileURLToPath(import.meta.url)), "..");
const root = join(mobile, "..");
const icons = join(root, "webapp/src/assets/file-icons");
// Node 22.18+ strips the resolver's TypeScript types on import.
const { WORKSPACE_ICON_KEYS } = await import(
  join(root, "packages/chat-core/src/fileIcons.ts")
);

const entries = WORKSPACE_ICON_KEYS.map((key) => {
  const svg = readFileSync(join(icons, `${key}.svg`), "utf8")
    .replace(/<\?xml[^>]*>/, "")
    .replace(/\s+/g, " ")
    .trim();
  return `  ${JSON.stringify(key)}: ${JSON.stringify(svg)},`;
});

writeFileSync(
  join(mobile, "src/tools/files/fileIconSvgs.generated.ts"),
  `// Generated by mobile/scripts/generate-file-icons.mjs from webapp/src/assets/file-icons
// (material-icon-theme, MIT, Material Extensions). Do not edit.
export const FILE_ICON_SVGS: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`,
);
console.log(`Wrote ${entries.length} icons.`);
